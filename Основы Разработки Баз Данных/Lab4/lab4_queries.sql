USE [VideoHostingDB];
GO

/* 1. Выборка из одной таблицы. */
SELECT
    c.[ID_контента],
    c.[название],
    c.[оригинальное_название],
    c.[год_выпуска],
    c.[страна_производства],
    c.[тип_контента]
FROM [dbo].[Контент] AS c
ORDER BY c.[название];
GO

/* 2. Выборка с параметрами разных типов и проверкой корректности. */
DECLARE @Название nvarchar(200) = N'а';
DECLARE @МинимальныйГод smallint = 2000;
DECLARE @ДатаПоступления date = '2000-01-01';

IF NULLIF(LTRIM(RTRIM(@Название)), N'') IS NULL
    THROW 51000, N'Название для поиска не должно быть пустым.', 1;

IF @МинимальныйГод < 1888 OR @МинимальныйГод > YEAR(GETDATE())
    THROW 51001, N'Некорректное значение минимального года.', 1;

SELECT
    c.[ID_контента],
    c.[название],
    c.[год_выпуска],
    c.[дата_поступления]
FROM [dbo].[Контент] AS c
WHERE c.[название] LIKE N'%' + @Название + N'%'
  AND c.[год_выпуска] >= @МинимальныйГод
  AND c.[дата_поступления] >= @ДатаПоступления
ORDER BY c.[год_выпуска] DESC, c.[название];
GO

/* 3. Выборка из нескольких таблиц: контент и жанры. */
SELECT
    c.[название] AS [Контент],
    g.[Наименование] AS [Жанр]
FROM [dbo].[Контент] AS c
INNER JOIN [dbo].[Контент_Жанр] AS cg
    ON cg.[ID_контента] = c.[ID_контента]
INNER JOIN [dbo].[Жанр] AS g
    ON g.[ID_жанра] = cg.[ID_жанра]
ORDER BY c.[название], g.[Наименование];
GO

/* 4. Полный запрос SELECT/FROM/WHERE/GROUP BY/HAVING/ORDER BY. */
DECLARE @ГодОтчёта smallint = 2000;

SELECT
    c.[страна_производства],
    COUNT(*) AS [Количество контента],
    MIN(c.[год_выпуска]) AS [Первый год],
    MAX(c.[год_выпуска]) AS [Последний год]
FROM [dbo].[Контент] AS c
WHERE c.[год_выпуска] >= @ГодОтчёта
GROUP BY c.[страна_производства]
HAVING COUNT(*) >= 1
ORDER BY [Количество контента] DESC, c.[страна_производства];
GO

/* 5. Агрегаты и NULL. */
SELECT
    COUNT(*) AS [Всего контента],
    COUNT(c.[год_выпуска]) AS [Контент с годом выпуска],
    AVG(CONVERT(decimal(10, 2), c.[год_выпуска])) AS [Средний год выпуска],
    ISNULL(MIN(c.[год_выпуска]), 0) AS [Минимальный год]
FROM [dbo].[Контент] AS c;
GO

/* 6. Некоррелированный подзапрос: контент, у которого есть жанр. */
SELECT
    c.[ID_контента],
    c.[название]
FROM [dbo].[Контент] AS c
WHERE c.[ID_контента] IN
(
    SELECT cg.[ID_контента]
    FROM [dbo].[Контент_Жанр] AS cg
)
ORDER BY c.[название];
GO

/* 7. Коррелированный подзапрос EXISTS. */
SELECT
    c.[ID_контента],
    c.[название]
FROM [dbo].[Контент] AS c
WHERE EXISTS
(
    SELECT 1
    FROM [dbo].[Медиа_файл] AS mf
    WHERE mf.[ID_контента] = c.[ID_контента]
)
ORDER BY c.[название];
GO

/* 8. Скалярный подзапрос: контент новее среднего года. */
SELECT
    c.[название],
    c.[год_выпуска]
FROM [dbo].[Контент] AS c
WHERE c.[год_выпуска] >
(
    SELECT AVG(CONVERT(decimal(10, 2), c2.[год_выпуска]))
    FROM [dbo].[Контент] AS c2
)
ORDER BY c.[год_выпуска] DESC;
GO

/* 9. INSERT/UPDATE/DELETE с параметрами и проверкой типов.
      Транзакция откатывается в конце учебного прогона. */
BEGIN TRY
    BEGIN TRANSACTION;

    DECLARE @НовоеНазвание nvarchar(200) = N'Тест ЛР4';
    DECLARE @НовыйГод smallint = 2026;
    DECLARE @НоваяСтрана nvarchar(100) = N'Тестовая страна';
    DECLARE @НовыйТип nvarchar(50) = N'Фильм';

    IF NULLIF(LTRIM(RTRIM(@НовоеНазвание)), N'') IS NULL
        THROW 51002, N'Название новой записи не должно быть пустым.', 1;

    IF @НовыйГод < 1888 OR @НовыйГод > YEAR(GETDATE())
        THROW 51003, N'Некорректный год новой записи.', 1;

    INSERT INTO [dbo].[Контент]
    (
        [название], [оригинальное_название], [год_выпуска],
        [страна_производства], [режиссёр], [краткое_описание],
        [возрастной_рейтинг], [тип_контента], [длительность],
        [дата_поступления], [постер]
    )
    VALUES
    (
        @НовоеНазвание, @НовоеНазвание, @НовыйГод,
        @НоваяСтрана, N'Тест', N'Тестовая запись для ЛР4',
        N'12+', @НовыйТип, NULL, CAST(GETDATE() AS date), NULL
    );

    DECLARE @IDТестовойЗаписи int = CONVERT(int, SCOPE_IDENTITY());

    UPDATE [dbo].[Контент]
    SET [краткое_описание] = N'Изменено параметрическим UPDATE в ЛР4'
    WHERE [ID_контента] = @IDТестовойЗаписи;

    DELETE FROM [dbo].[Контент]
    WHERE [ID_контента] = @IDТестовойЗаписи;

    ROLLBACK TRANSACTION;
END TRY
BEGIN CATCH
    IF XACT_STATE() <> 0
        ROLLBACK TRANSACTION;
    THROW;
END CATCH;
GO

